/**
 * Candid — Proofly's own encoder and decoder.
 *
 * Candid is the Thebes Protocol's wire format: the boundary hands a contract a
 * byte string and the contract's Rust CDK decodes it as Candid. This module is
 * that format, implemented here, so the app carries no external codec.
 *
 * ── Why this file exists rather than a dependency ───────────────────────────
 *
 * Proofly used a third-party Candid package until this file replaced it. Two
 * reasons it had to go:
 *
 *   1. Proofly is a Thebes application. It depends on no other chain's
 *      ecosystem packages.
 *   2. That package is deprecated by its own maintainers — installing it
 *      printed a notice pointing at a successor. A deprecated dependency, for a
 *      format we use one narrow slice of, is not worth carrying.
 *
 * ── What it covers, and what it deliberately does not ───────────────────────
 *
 * This implements exactly the slice `backend/backend.did` uses:
 *
 *      text · nat8 · nat64 · null · vec · record · variant
 *
 * That is a deliberate floor, not an unfinished one. `opt`, `int*`, `float*`,
 * `principal`, `func`, `service`, `reserved`, `empty` and recursive types are
 * NOT implemented, and every one of them **throws on sight** rather than
 * guessing — a silently wrong decode of an employment record is worse than a
 * loud failure. If the contract's interface ever grows one of them, this file
 * fails immediately and visibly, which is the intended behaviour.
 *
 * ── How it is known to be correct ───────────────────────────────────────────
 *
 * `scripts/candid-fixtures.json` holds golden byte vectors generated by the
 * reference implementation for every method in the interface, in both variant
 * arms, including an empty vector, an empty string and non-ASCII text.
 * `npm run check:codec` asserts this codec reproduces those bytes exactly and
 * decodes them back to the same values. Those vectors are ground truth from an
 * implementation this one never shared code with.
 *
 * The wire format is Candid, as Thebes speaks it. Every type opcode this file
 * handles is named and numbered immediately below.
 */

// ─────────────────────────────────────────────────────────────────────────────
// Wire primitives
// ─────────────────────────────────────────────────────────────────────────────

/** Type opcodes, as they appear SLEB128-encoded on the wire. */
const OP_NULL = -1;
const OP_NAT8 = -5;
const OP_NAT64 = -8;
const OP_TEXT = -15;
const OP_OPT = -18;
const OP_VEC = -19;
const OP_RECORD = -20;
const OP_VARIANT = -21;

const MAGIC = [0x44, 0x49, 0x44, 0x4c]; // "DIDL"

const utf8Encode = new TextEncoder();
/** `fatal` matters: a malformed reply must fail, not yield replacement chars. */
const utf8Decode = new TextDecoder('utf-8', { fatal: true });

function leb128(value: number | bigint, out: number[]): void {
    let v = BigInt(value);
    if (v < 0n) throw new RangeError('leb128 is unsigned');
    do {
        let byte = Number(v & 0x7fn);
        v >>= 7n;
        if (v > 0n) byte |= 0x80;
        out.push(byte);
    } while (v > 0n);
}

function sleb128(value: number | bigint, out: number[]): void {
    let v = BigInt(value);
    for (;;) {
        const byte = Number(v & 0x7fn);
        v >>= 7n; // BigInt shift is arithmetic, so this terminates at -1 for negatives
        const signSet = (byte & 0x40) !== 0;
        if ((v === 0n && !signSet) || (v === -1n && signSet)) {
            out.push(byte);
            return;
        }
        out.push(byte | 0x80);
    }
}

/**
 * A Candid field label's numeric id: the 32-bit hash of its name.
 *
 * Field *names* never appear on the wire — only these hashes — which is why
 * decoding needs the expected type to recover them.
 */
function fieldHash(name: string): number {
    let h = 0n;
    for (const byte of utf8Encode.encode(name)) {
        h = (h * 223n + BigInt(byte)) & 0xffffffffn;
    }
    return Number(h);
}

class Reader {
    private readonly buf: Uint8Array;
    private pos: number;

    constructor(buf: Uint8Array) {
        this.buf = buf;
        this.pos = 0;
    }

    private need(n: number): void {
        if (this.pos + n > this.buf.length) {
            throw new Error(
                `truncated Candid: wanted ${n} byte(s) at offset ${this.pos}, ` +
                    `only ${this.buf.length - this.pos} remain`
            );
        }
    }

    byte(): number {
        this.need(1);
        return this.buf[this.pos++];
    }

    take(n: number): Uint8Array {
        this.need(n);
        const slice = this.buf.subarray(this.pos, this.pos + n);
        this.pos += n;
        return slice;
    }

    leb(): bigint {
        let result = 0n;
        let shift = 0n;
        for (;;) {
            const byte = this.byte();
            result |= BigInt(byte & 0x7f) << shift;
            if ((byte & 0x80) === 0) return result;
            shift += 7n;
            if (shift > 128n) throw new Error('leb128 value is implausibly long');
        }
    }

    sleb(): bigint {
        let result = 0n;
        let shift = 0n;
        for (;;) {
            const byte = this.byte();
            result |= BigInt(byte & 0x7f) << shift;
            shift += 7n;
            if ((byte & 0x80) === 0) {
                if ((byte & 0x40) !== 0) result -= 1n << shift; // sign-extend
                return result;
            }
            if (shift > 128n) throw new Error('sleb128 value is implausibly long');
        }
    }

    /** Length as a JS number, rejecting anything that cannot be one. */
    count(): number {
        const n = this.leb();
        if (n > 0x7fffffffn) throw new Error(`implausible Candid length: ${n}`);
        return Number(n);
    }

    /**
     * A field label id.
     *
     * Read separately from `count()` because it is a full unsigned 32-bit
     * hash: `employee_name` hashes to 2,643,220,632, which is larger than any
     * length this codec will accept. Reading one as a length rejects every
     * record with a high-hashing field name.
     */
    labelId(): number {
        const n = this.leb();
        if (n > 0xffffffffn) throw new Error(`field label id out of range: ${n}`);
        return Number(n);
    }

    get exhausted(): boolean {
        return this.pos >= this.buf.length;
    }
}

// ─────────────────────────────────────────────────────────────────────────────
// The wire's own view of a type
//
// Parsed from the message's type table. A reference is negative for a
// primitive (it *is* the opcode) and non-negative for an index into the table.
// ─────────────────────────────────────────────────────────────────────────────

type WireType =
    | { k: 'prim'; code: number }
    | { k: 'vec'; elem: number }
    | { k: 'opt'; elem: number }
    | { k: 'record'; fields: Array<[number, number]> }
    | { k: 'variant'; fields: Array<[number, number]> };

/** Resolves a wire type reference against the message's type table. */
type Deref = (ref: number) => WireType;

function parseTableEntry(r: Reader): WireType {
    const op = Number(r.sleb());
    switch (op) {
        case OP_VEC:
            return { k: 'vec', elem: Number(r.sleb()) };
        case OP_OPT:
            return { k: 'opt', elem: Number(r.sleb()) };
        case OP_RECORD:
        case OP_VARIANT: {
            const n = r.count();
            const fields: Array<[number, number]> = [];
            for (let i = 0; i < n; i++) {
                fields.push([r.labelId(), Number(r.sleb())]);
            }
            return { k: op === OP_RECORD ? 'record' : 'variant', fields };
        }
        default:
            throw new Error(
                `unsupported Candid type opcode ${op} in the type table. ` +
                    `This codec implements text/nat8/nat64/null/vec/record/variant only.`
            );
    }
}

