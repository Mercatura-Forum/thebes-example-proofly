/**
 * The Candid type constructors and the two message functions.
 *
 * `Vec`, `Record` and `Variant` are memoised on their structural name so that
 * `IDL.Vec(IDL.Nat8)` written twice is one type, not two — the same identity
 * the type table's deduplication assumes.
 */
export const IDL = {
    Text: new TextType(),
    Nat8: new Nat8Type(),
    Nat64: new Nat64Type(),
    Null: new NullType(),

    Vec<T>(elem: CandidType<T>): CandidType<T[] | Uint8Array> {
        return new VecType(elem);
    },

    Record(fields: Record<string, CandidType<any>>): CandidType<Record<string, any>> {
        return new RecordType(fields);
    },

    Variant(fields: Record<string, CandidType<any>>): CandidType<Record<string, any>> {
        return new VariantType(fields);
    },

    encode,
    decode,
} as const;
